_INITIALIZATION_LOCK = threading.Lock()


def init_database(settings: Settings | None = None) -> None:
    settings = _settings(settings)
    database_url = _database_url(settings)
    if database_url in _INITIALIZED_URLS:
        return

    with _INITIALIZATION_LOCK:
        if database_url in _INITIALIZED_URLS:
            return
        with _connection(database_url) as connection:
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS schema_version (
                    id integer PRIMARY KEY CHECK (id = 1),
                    version integer NOT NULL
                )
                """
            )
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS clients (
                    client_id text PRIMARY KEY,
                    name text NOT NULL,
                    username text NOT NULL,
                    password text NOT NULL,
                    priority integer NOT NULL DEFAULT 0,
                    active boolean NOT NULL DEFAULT true,
                    done boolean NOT NULL DEFAULT false,
                    created_at text NOT NULL,
                    updated_at text NOT NULL
                )
                """
            )
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS client_state (
                    client_id text PRIMARY KEY REFERENCES clients(client_id) ON DELETE CASCADE,
                    last_status text,
                    last_message text,
                    consecutive_errors integer NOT NULL DEFAULT 0,
                    next_allowed_at text,
                    last_run_at text,
                    last_success_at text,
                    programmed_at text
                )
                """
            )
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS runs (
                    run_id text PRIMARY KEY,
                    client_id text REFERENCES clients(client_id) ON DELETE SET NULL,
                    status text NOT NULL,
                    message text NOT NULL,
                    exit_code integer NOT NULL,
                    started_at text NOT NULL,
                    finished_at text NOT NULL,
                    duration_seconds double precision NOT NULL,
                    reservation_attempted boolean NOT NULL DEFAULT false,
                    reservation_confirmed boolean NOT NULL DEFAULT false,
                    details_json jsonb,
                    screenshot_path text,
                    created_at text NOT NULL
                )
                """
            )
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS run_screenshots (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    run_id text NOT NULL REFERENCES runs(run_id) ON DELETE CASCADE,
                    path text NOT NULL,
                    created_at text NOT NULL
                )
                """
            )
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS worker_state (
                    id integer PRIMARY KEY CHECK (id = 1),
                    phase text NOT NULL DEFAULT 'stopped',
                    paused boolean NOT NULL DEFAULT false,
                    current_client_id text,
                    masked_account text,
                    session_started_at text,
                    last_check_at text,
                    next_check_at text,
                    confirmed_reservations integer NOT NULL DEFAULT 0,
                    consecutive_errors integer NOT NULL DEFAULT 0,
                    last_error text,
                    availability_signature text,
                    owner_token text,
                    updated_at text NOT NULL
                )
                """
            )
            connection.execute(
                "INSERT INTO worker_state (id, updated_at) VALUES (1, %s) ON CONFLICT DO NOTHING",
                (_now(),),
            )
            connection.execute(
                """
                CREATE INDEX IF NOT EXISTS idx_clients_queue
                    ON clients(active, done, priority DESC, created_at ASC)
                """
            )
            connection.execute(
                """
                CREATE INDEX IF NOT EXISTS idx_runs_client_started
                    ON runs(client_id, started_at DESC)
                """
            )
            _migrate_database(connection)
        _INITIALIZED_URLS.add(database_url)


def add_client(
    client_id: str,
    name: str,
    username: str,
    password: str,
    priority: int,
    *,
    settings: Settings | None = None,
) -> None:
    settings = _settings(settings)
    init_database(settings)
    now = _now()
    with _connection(_database_url(settings)) as connection:
        connection.execute(
            """
            INSERT INTO clients (
                client_id, name, username, password, priority, active, done, created_at, updated_at
            )
            VALUES (%s, %s, %s, %s, %s, true, false, %s, %s)
            ON CONFLICT(client_id) DO UPDATE SET
                name = excluded.name,
                username = excluded.username,
                password = excluded.password,
                priority = excluded.priority,
                active = true,
                done = false,
                updated_at = excluded.updated_at
            """,
            (client_id, name, username, password, priority, now, now),
        )
        connection.execute(
            "INSERT INTO client_state (client_id) VALUES (%s) ON CONFLICT DO NOTHING",
            (client_id,),
        )
        connection.execute(
            """
            UPDATE client_state
            SET last_status = NULL,
                last_message = NULL,
                consecutive_errors = 0,
                next_allowed_at = NULL,
                programmed_at = NULL
            WHERE client_id = %s
            """,
            (client_id,),
        )


