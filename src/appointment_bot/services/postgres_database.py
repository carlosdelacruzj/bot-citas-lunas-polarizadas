def _run_filters(*, client_id: str | None, status: str | None) -> tuple[str, list[Any]]:
    filters = []
    values: list[Any] = []
    if client_id:
        filters.append("r.client_id = %s")
        values.append(client_id)
    if status:
        filters.append("r.status = %s")
        values.append(status)
    if not filters:
        return "", values
    return "WHERE " + " AND ".join(filters), values


def _executemany(connection: Connection, query: str, rows: list[tuple[Any, ...]]) -> None:
    if not rows:
        return
    with connection.cursor() as cursor:
        cursor.executemany(query, rows)


def _mask_username(username: str) -> str:
    if not username:
        return ""
    if len(username) <= 3:
        return "***"
    return f"{username[:2]}***{username[-1]}"


def _public_path(value: str | None) -> str | None:
    if not value:
        return None
    return str(value).replace("\\", "/").split("/")[-1]


def _now() -> str:
    return datetime.now().isoformat(timespec="seconds")
