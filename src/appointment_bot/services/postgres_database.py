def _migrate_database(connection: Connection) -> None:
    row = connection.execute("SELECT version FROM schema_version WHERE id = 1").fetchone()
    version = int(row["version"]) if row else 0
    if version < 1:
        version = 1
    if version < 2:
        connection.execute(
            """
            ALTER TABLE worker_state
            ADD COLUMN IF NOT EXISTS owner_token text
            """
        )
        version = 2
    if version < 3:
        _add_check_constraint(
            connection,
            "clients",
            "clients_priority_non_negative",
            "priority >= 0",
        )
        _add_check_constraint(
            connection,
            "clients",
            "clients_not_active_when_done",
            "NOT (active AND done)",
        )
        _add_check_constraint(
            connection,
            "client_state",
            "client_state_known_status",
            """
            last_status IS NULL OR last_status IN (
                'available', 'completed', 'error', 'partial', 'paused', 'registered',
                'reservation_unconfirmed', 'skipped', 'unavailable', 'unknown',
                'programmed', 'submission_intent', 'submission_pending'
            )
            """,
        )
        _add_check_constraint(
            connection,
            "runs",
            "runs_known_status",
            """
            status IN (
                'available', 'completed', 'error', 'partial', 'paused', 'registered',
                'reservation_unconfirmed', 'skipped', 'unavailable', 'unknown'
            )
            """,
        )
        version = 3
    connection.execute(
        """
        INSERT INTO schema_version (id, version)
        VALUES (1, %s)
        ON CONFLICT(id) DO UPDATE SET version = excluded.version
        """,
        (max(version, SCHEMA_VERSION),),
    )


